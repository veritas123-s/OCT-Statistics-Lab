'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const base=fs.existsSync(path.join(__dirname,'docs','statistics.js'))?'docs':'dist';
const {compute}=require('./'+base+'/statistics.js');
const raw={window:{}};vm.runInNewContext(fs.readFileSync(path.join(__dirname,base,'original-data.js'),'utf8'),raw);
const source=raw.window.OCT_SOURCE;
assert.equal(source.rows.length,149);assert.equal(source.headers.length,25);
const sourceRows=[2,4,6,8,10].map(r=>source.rows.find(d=>d.row===r));
const points=sourceRows.map(r=>({x:r.values[10],y:r.values[11]}));
assert.deepEqual(points,[{x:84,y:33},{x:71,y:28},{x:86,y:52},{x:105,y:63},{x:90,y:43}]);
const close=(x,y,tol=1e-9)=>assert.ok(Math.abs(x-y)<=tol*Math.max(1,Math.abs(y)),`${x} != ${y}`);
const s=compute(points);
close(s.mean[0],87.2);close(s.mean[1],43.8);
close(s.a,149.7);close(s.b,155.05);close(s.c,200.7);close(s.det,6004.2875);
close(s.eigen[0],332.3329134840948);close(s.eigen[1],18.06708651590526);
close(s.q1[0]*s.q2[0]+s.q1[1]*s.q2[1],0);
for(let i=0;i<2;i++)for(let j=0;j<2;j++)close(s.eigen[0]*s.q1[i]*s.q1[j]+s.eigen[1]*s.q2[i]*s.q2[j],s.S[i][j]);
for(let i=0;i<2;i++)for(let j=0;j<2;j++)close(s.white.reduce((v,w)=>v+w[i]*w[j],0)/4,i===j?1:0);
const p6={x:88,y:69},p8={x:115,y:63};
close(s.distance(p6).md,3.8487835455857016);close(s.distance(p8).md,2.73079497211715);
assert.ok(s.distance(p6).euclidean<s.distance(p8).euclidean);assert.ok(s.distance(p6).md>s.distance(p8).md);
// Translation and invertible rescaling leave Mahalanobis distance invariant.
const modified=points.map(p=>({x:3*p.x+11,y:-2*p.y+40}));
close(compute(modified).distance({x:3*p6.x+11,y:-2*p6.y+40}).md,s.distance(p6).md);
assert.equal(compute([{x:1,y:2},{x:2,y:4},{x:3,y:6}]).positive,false);
assert.equal(compute([{x:1,y:2},{x:2,y:4},{x:3,y:6}]).distance(p6).md,null);
assert.equal(compute([{x:1,y:1},{x:1,y:1},{x:1,y:1}]).distance(p6).md,null);
assert.throws(()=>compute([{x:NaN,y:1},{x:2,y:3}]));
assert.throws(()=>compute([{x:1,y:2}]));
assert.equal(source.rows.find(r=>r.row===149).values[10],null);
for(const asset of ['index.html','lab.css','lab.js','statistics.js','original-data.js','source-data.xlsx'])assert.ok(fs.statSync(path.join(__dirname,base,asset)).size>0);
console.log('Verified: source observations; reference statistics; eigendecomposition; whitening; distance examples; affine invariance; singular and missing inputs; static assets.');
